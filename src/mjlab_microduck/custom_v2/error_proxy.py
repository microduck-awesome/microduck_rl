"""GPU replay of paired, temporally contiguous P04 output-error blocks.

These errors were generated by the frozen bench model, not newly measured on
hardware. Keep their position/velocity covariance and 20 ms sampling; do not
claim full conditional residual selection, read faults or firmware identity.
"""
import hashlib
import json
from pathlib import Path
import numpy as np
import torch


class ErrorBlocks:
    def __init__(self,bank,n,device,seed):
        self.bank=bank.to(device)
        if self.bank.ndim!=3 or self.bank.shape[1:]!=(16,2):
            raise ValueError('Expected paired 16-control error blocks')
        self.n,self.device=n,device
        self.rng=torch.Generator(device=device).manual_seed(seed)
        self.block=torch.zeros(n,14,dtype=torch.long,device=device)
        self.phase=torch.zeros_like(self.block)
        self.value=torch.zeros(n,14,2,device=device)
        self.reset_at=torch.full((n,),-1,dtype=torch.long,device=device)
        self.last_step=None

    def reset(self,ids,step):
        self.block[ids]=torch.randint(len(self.bank),(len(ids),14),generator=self.rng,device=self.device)
        self.phase[ids]=torch.randint(16,(len(ids),14),generator=self.rng,device=self.device)
        self.value[ids]=self.bank[self.block[ids],self.phase[ids]]
        self.reset_at[ids]=step

    def sample(self,step):
        if self.last_step==step:return self.value
        advance=(self.reset_at!=step)[:,None]
        phase=torch.where(advance,(self.phase+1)%16,self.phase)
        candidates=torch.randint(len(self.bank),(self.n,14),generator=self.rng,device=self.device)
        self.block.copy_(torch.where(advance&(phase==0),candidates,self.block))
        self.phase.copy_(phase)
        self.value.copy_(self.bank[self.block,self.phase])
        self.last_step=step
        return self.value


def proxy_state(env,bank_path):
    if not hasattr(env,'_v2_error_blocks'):
        root=Path(bank_path)
        manifest=json.loads((root/'manifest.json').read_text())
        digest=hashlib.sha256((root/'error-blocks.npz').read_bytes()).hexdigest()
        if digest!=manifest['bank_sha256']:raise ValueError('Error proxy bank changed')
        with np.load(root/'error-blocks.npz',allow_pickle=False) as data:
            bank=torch.from_numpy(data['blocks'].copy())
        state=ErrorBlocks(bank,env.num_envs,env.device,(env.cfg.seed or 42)+71091)
        state.reset(torch.arange(env.num_envs,device=env.device),env.common_step_counter)
        env._v2_error_blocks=state
        env._v2_sensor_proxy={**manifest,'manifest_sha256':hashlib.sha256((root/'manifest.json').read_bytes()).hexdigest()}
    return env._v2_error_blocks


def reset_proxy(env,env_ids,bank_path):
    if env_ids is None:env_ids=torch.arange(env.num_envs,device=env.device)
    proxy_state(env,bank_path).reset(env_ids,env.common_step_counter)


def proxy_joint_pos(env,bank_path,strength=1.):
    from mjlab_microduck.tasks import mdp
    robot=env.scene['robot'];ids=mdp._servo_joint_ids(env,robot)
    noise=proxy_state(env,bank_path).sample(env.common_step_counter)[...,0]
    return robot.data.joint_pos[:,ids]-robot.data.default_joint_pos[:,ids]+strength*noise


def proxy_joint_vel(env,bank_path,strength=1.):
    from mjlab_microduck.tasks import mdp
    robot=env.scene['robot'];ids=mdp._servo_joint_ids(env,robot)
    noise=proxy_state(env,bank_path).sample(env.common_step_counter)[...,1]
    return robot.data.joint_vel[:,ids]+strength*noise
